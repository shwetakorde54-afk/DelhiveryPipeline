import numpy as np
import pandas as pd
from sklearn.model_selection import KFold, cross_val_score
from sklearn.linear_model import LinearRegression
from sklearn.tree import DecisionTreeRegressor
from sklearn.ensemble import RandomForestRegressor, GradientBoostingRegressor
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

metrics = pd.read_csv("/content/outputs/part_b_metrics.csv")
val = metrics[metrics["split"] == "val"].copy()
order = ["mean_baseline", "linear_regression", "decision_tree", "random_forest", "gradient_boosting"]
val = val.set_index("model").loc[order].reset_index()

candidates = val[val["model"] != "mean_baseline"].sort_values("RMSE")
two_best = candidates["model"].head(2).tolist()
final_name = two_best[0]

trees = pd.read_csv("/content/outputs/part_b_tree_depth.csv")
trees["depth_key"] = trees["max_depth"].map(lambda v: 999 if str(v) == "unlimited" else int(float(v)))
best_tree = trees.sort_values(["val_rmse", "depth_key"]).iloc[0]
depth = None if str(best_tree["max_depth"]) == "unlimited" else int(best_tree["depth_key"])

def make_model(name):
    if name == "linear_regression":
        return Pipeline([("scaler", StandardScaler()), ("model", LinearRegression())])
    if name == "decision_tree":
        return DecisionTreeRegressor(max_depth=depth, random_state=42)
    if name == "random_forest":
        return RandomForestRegressor(n_estimators=100, random_state=42)
    if name == "gradient_boosting":
        return GradientBoostingRegressor(n_estimators=100, learning_rate=0.1, random_state=42)

X_tv = pd.concat([X_train, X_val], axis=0)
y_tv = pd.concat([y_train, y_val], axis=0)
shared_folds = KFold(n_splits=5, shuffle=True, random_state=42)

cv_rows = []
for name in two_best:
    scores = cross_val_score(make_model(name), X_tv, y_tv, cv=shared_folds)
    cv_rows.append({
        "model": name,
        "mean_r2": round(float(scores.mean()), 4),
        "std_r2": round(float(scores.std()), 4),
    })
cv_table = pd.DataFrame(cv_rows)
cv_table.to_csv("/content/outputs/part_b_cv.csv", index=False)

def score_row(name, split, y_true, y_pred):
    mae = round(float(mean_absolute_error(y_true, y_pred)), 4)
    mse = round(float(mean_squared_error(y_true, y_pred)), 4)
    rmse = round(float(np.sqrt(mse)), 4)
    r2 = round(float(r2_score(y_true, y_pred)), 4)
    return {"model": name, "split": split, "MAE": mae, "MSE": mse, "RMSE": rmse, "R2": r2}

final_model = make_model(final_name)
final_model.fit(X_train, y_train)
