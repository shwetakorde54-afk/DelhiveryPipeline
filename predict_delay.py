import os
import joblib
import numpy as np
import pandas as pd

raw = pd.read_csv("/content/data/new_shipments.csv")
hubs = pd.read_csv("/content/data/hubs.csv")
file_order = raw["shipment_id"].drop_duplicates().tolist()

stored = pd.read_csv("/content/models/impute_values.csv")
medians = dict(zip(stored["column"], stored["median"].astype(float)))
threshold = float(pd.read_csv("/content/models/delay_threshold.csv")["threshold"].iloc[0])
threshold = round(threshold, 1)
feature_order = pd.read_csv("/content/models/feature_order.csv")["feature"].tolist()
segments = pd.read_csv("/content/outputs/hub_segments.csv")[["hub_id", "segment"]]

clean, _ = clean_shipments(raw, medians=medians)
features = build_features(clean, hubs)
X = features[feature_order]

model = joblib.load("/content/models/delay_model.pkl")
classes = list(model.named_steps["model"].classes_)
probability = model.predict_proba(X)[:, classes.index(1)]

actions = features[["shipment_id", "hub_id"]].copy()
actions["delay_probability"] = [round(float(p), 4) for p in probability]
actions["flagged"] = (actions["delay_probability"] >= threshold).astype(int)
actions = actions.merge(segments, on="hub_id", how="left")
actions["action"] = np.where(
    actions["flagged"] == 0,
    "No action",
    np.where(
        actions["segment"] == "Escalate",
        "Escalate to hub manager",
        "Proactive customer call",
    ),
)
actions = actions.set_index("shipment_id").loc[file_order].reset_index()
actions = actions[["shipment_id", "hub_id", "segment", "delay_probability", "flagged", "action"]]

os.makedirs("/content/outputs", exist_ok=True)
actions.to_csv("/content/outputs/new_shipment_actions.csv", index=False, lineterminator="\n")
display(actions)
