import math
import pandas as pd
from sklearn.cluster import KMeans

def euclidean(a, b):
    total = 0
    for column in range(len(a)):
        total += (a[column] - b[column]) ** 2
    return math.sqrt(total)

rows = []
for k in [2, 3, 4, 5]:
    kmeans = KMeans(n_clusters=k, random_state=42, n_init=10).fit(X)
    labels = kmeans.labels_

    across = []
    within = []
    for i in range(len(labels)):
        for j in range(i + 1, len(labels)):
            distance = euclidean(X[i], X[j])
            if labels[i] == labels[j]:
                within.append(distance)
            else:
                across.append(distance)

    sizes = pd.Series(labels).value_counts().sort_values(ascending=False)
    rows.append({
        "K": k,
        "across_over_within": sum(across) / len(across) / (sum(within) / len(within)),
        "cluster_sizes": "-".join(str(int(s)) for s in sizes),
    })

separation = pd.DataFrame(rows)
separation.to_csv("/content/outputs/part_d_separation.csv", index=False)
display(separation)

